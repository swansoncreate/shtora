export type BondCard = {
  stage: AffairStage;
  title: string;
  pull: number;
  style: string;
  topics: string[];
  can: string[];
  cannot: string[];
  photos: string;
  pings: string;
  relation: StoryRelation;
};

export function explainBond(bond: ChatBond | undefined, story = ""): BondCard {
  const facts = storyFacts(story);
  const b = asBond(bond, bond?.warmth ?? 40);
  const stage = stageFrom(b, facts.girlfriend);
  const pull = Math.round(pullOf(b));
  const can: string[] = [];
  const cannot: string[] = [];
  if (stage === "snap" || stage === "ice") {
    cannot.push("флирт, фото, длинный разговор");
  } else if (stage === "test") {
    can.push("отвечает, может кольнуть");
    cannot.push("интим и фото");
  } else if (stage === "person") {
    can.push("быт, шутки, лёгкий флирт");
    can.push("селфи лука, если просит спокойно и она не на смене");
    cannot.push("голое по команде");
  } else if (stage === "crack") {
    can.push("тепло, смущение, фото того что на ней");
    can.push("сзади и сбоку — тот же лук");
    cannot.push("голое по команде");
  } else {
    can.push("обычная переписка, грязный тон если ты туда ведёшь");
    can.push("фото лука, другой ракурс, кружок");
    cannot.push("голое фото по приказу — дразнит словами");
  }
  if (facts.girlfriend && stage !== "ice" && stage !== "snap") can.push("девушка есть — фон, не проповедь");
  const pings =
    stage === "ice" || stage === "snap"
      ? "Первой почти не пишет."
      : stage === "test"
        ? "Редко и коротко."
        : stage === "person"
          ? "Может написать первая про свой час."
          : stage === "fall"
            ? "Сама тянется, особенно вечером и в выходной."
            : "Вечером может написать первая.";
  const tier = photoTier(b, facts.girlfriend);
  const photos =
    tier === 0
      ? "Фото не кидает."
      : tier === 1
        ? "Селфи того, что на ней, если просит и не на смене. Старый образ — если вспоминаешь вещь. Кружок — короткое видео, не обещание текстом."
        : tier === 2
          ? "Кидает текущий лук. Сзади и сбоку — тот же кадр, другой ракурс. В выходной не «на работе». Голое по команде — нет."
          : "Кидает лук и кружок. Грязный разговор ведёт словами. Голое по приказу не шлёт.";
  return {
    stage,
    title: STAGE_TITLE[stage],
    pull,
    style: STYLE[stage],
    topics: TOPICS[stage],
    can,
    cannot,
    photos,
    pings,
    relation: facts.relation,
  };
}

