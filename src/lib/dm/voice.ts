export function fallbackBubble(stage: string) {
  if (stage === "ice" || stage === "test") return "увидела";
  if (stage === "snap") return "хватит";
  if (stage === "crack") return "ладно";
  if (stage === "secret" || stage === "fall") return "ну";
  return "норм";
}
